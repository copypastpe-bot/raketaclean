"""Скрыть телефон и адрес клиента из строки перед отправкой в технический
журнал (ТЗ 2026-09-18, задача 5).

Почему по тексту, а не по полю: адаптер получает из journald уже готовые
строки текста, а не исходные объекты бота (заказ, контакт, вебхук) — доступа
к структуре данных у него нет и не может быть. Поэтому маскировка работает
как фильтр по форме текста, а не по имени переменной.

Разведка перед этим модулем (грепом по всем `logger.warning/error/exception/
critical` в bot.py, cleaning/, crm/, notifications/, всего 130 вызовов):
почти везде в журнал попадают только числовые id (заказа, сделки, клиента) —
это не ПД сама по себе. Один настоящий случай нашёлся —
`notifications/outbox.py:626` кладёт в предупреждение весь необработанный
payload вебхука целиком (`"...payload=%s", payload`), а такой payload у
провайдера мессенджера обычно несёт номер получателя. Код бота эта задача не
трогает (правило ТЗ), поэтому защита — здесь, маскировкой по форме, а не
правкой того вызова.

Телефон: та же логика, что уже проверена в проекте (`bot.py:normalize_phone_
for_db` разбирает произвольный текст на цифры вида «7/8 плюс 10 цифр» или
«9 плюс 9 цифр») и та же маска, что везде в этом проекте (`bot.py:mask_phone_last4`,
`raketa-admin-bot/adminbot/phone.py:mask`, `notifications/order_address.py:
_mask`) — "…" плюс последние 4 цифры.

Адрес: у рабочего бота прямого попадания «адрес клиента → warning-журнал» не
нашлось (проверено тем же грепом), но требование ТЗ безусловно — эвристика
по маркерам улицы/дома/квартиры работает независимо от того, нашли мы
конкретное место или нет, и та же идея уже используется в `bot.py:
extract_street` («простая эвристика», её собственные слова).
"""

from __future__ import annotations

import re

# Разделители внутри отображаемого номера: пробел, скобки, тире. Точку
# сознательно не берём в разделители — иначе маска будет путать номер
# телефона с суммой денег вида "12345678.90".
_SEP = r"[\s()\-]*"

_PHONE_RE = re.compile(
    r"(?<!\d)(?:"
    r"\+?" + _SEP + r"[78]" + _SEP + r"(?:\d" + _SEP + r"){9}\d"   # +7/7/8 и 10 цифр дальше = 11
    r"|"
    r"9" + _SEP + r"(?:\d" + _SEP + r"){8}\d"                       # 9 и 9 цифр дальше = 10
    r")(?!\d)"
)


def _mask_phone_match(m: "re.Match[str]") -> str:
    digits = re.sub(r"\D", "", m.group(0))
    return f"…{digits[-4:]}" if len(digits) >= 4 else "…"


def mask_phones(text: str) -> str:
    """Телефон -> "…" плюс последние 4 цифры (формат как везде в проекте)."""
    return _PHONE_RE.sub(_mask_phone_match, text)


# Маркеры улицы: сама улица маскируется целиком, маркер остаётся — по нему
# видно, что здесь БЫЛ адрес, не что он содержит. Номер дома, если он идёт
# сразу за названием улицы (через запятую или без неё), маскируется вторым
# "…" — иначе он оставался читаемым (ревью 19.09, пункт 5).
#
# Семейство «проспект» разложено на явные написания, а не оставлено одним
# приблизительным вариантом: пр-т/пр-кт (с дефисом и без), голое «пр.»,
# «просп.»/«проспект» с необязательной точкой на конце.
_STREET_RE = re.compile(
    r"(ул\.|улица|просп(?:ект)?\.?|пр-?(?:кт|т)\.?|пр\.|пер(?:еулок)?\.?|бульвар|б-р|шоссе|"
    r"наб(?:ережная)?\.?)(\s+[^\d,.;\n#]{1,40})(\s*,?\s*\d[\w/\-]*)?",
    re.IGNORECASE,
)

# Маркеры дома/квартиры: маскируется только номер после маркера.
# «д»/«кв» без точки добавлены отдельно с просмотром вперёд на цифру —
# так ловится слитное написание («д5», «кв12»), но не любое слово на «д»/«кв».
# «стр(?:оение)?\.?» — одна альтернатива вместо двух: раньше короткая форма
# «стр\.?» стояла перед «строение» и, встретив слово «строение», сама
# останавливалась на «стр», а свободный класс символов номера доедал
# остаток слова («оение») — номер дома после слова уже не доставался.
_HOUSE_RE = re.compile(
    r"(д\.|дом|д(?=\d)|кв\.|квартира|кв(?=\d)|корп\.?|корпус|стр(?:оение)?\.?|подъезд)"
    r"(\s*№?\s*)([\dА-Яа-яA-Za-z][\w/\-]*)",
    re.IGNORECASE,
)


def mask_addresses(text: str) -> str:
    """Улица и номер дома/квартиры -> маркер остаётся, значение скрыто.

    Эвристика на маркерных словах (как `bot.py:extract_street`), не разбор
    полного адреса: не претендует на то, чтобы поймать 100% форм записи,
    но и не должна — это защитный слой поверх кода ботов, который не трогаем.
    """
    def _replace_street(m: "re.Match[str]") -> str:
        # Третья группа непустая -> сразу за улицей шёл голый номер дома,
        # маскируем и его отдельным "…", маркер улицы к нему не относится.
        if m.group(3):
            return f"{m.group(1)} … …"
        return f"{m.group(1)} …"

    text = _STREET_RE.sub(_replace_street, text)
    text = _HOUSE_RE.sub(lambda m: f"{m.group(1)}{m.group(2)}…", text)
    return text


def redact(text: str) -> str:
    """Скрыть телефон и адрес клиента — единая точка входа для адаптера."""
    return mask_addresses(mask_phones(text))
