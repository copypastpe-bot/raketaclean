-- Нажатия кнопки «Я уже перезвонил» робота автозвонка — договорённость рабочего
-- бота с админ-ботом. ТЗ docs/plans/2026-10-23-autocall-manager-button.md
-- (задача 1, 2026-10-23).
--
-- Робот автозвонка (админ-бот) не дозвонился и собирается повторить — менеджеру
-- в личку рабочего бота приходит сообщение с кнопкой (админ-бот шлёт его ключом
-- рабочего бота, поэтому нажатие получает рабочий бот). Рабочий бот пишет строку,
-- когда кнопку нажали, пока цепочка звонков по сделке ещё живая
-- (adminbot.autocall_leads). Админ-бот читает строки (у роли adminbot есть SELECT
-- на новые таблицы public по умолчанию) и перед повтором останавливает робота.
-- Рабочий бот строки не меняет и не удаляет; повторное нажатие строку не трогает.
--
-- lead_id    — сделка amoCRM, по которой шла цепочка (ключ: одно нажатие на сделку);
-- tg_user_id — кто нажал (id в Telegram);
-- pressed_at — когда нажали (первое нажатие).

CREATE TABLE IF NOT EXISTS autocall_manager_callbacks (
    lead_id    bigint PRIMARY KEY,
    tg_user_id bigint NOT NULL,
    pressed_at timestamptz NOT NULL DEFAULT now()
);
