-- Робот доводит сделку после поступления оплаты по счёту. Применяется вручную:
--   psql "$ADMINBOT_DB_DSN" -f migrations/017_wire_payment.sql
--
-- Зачем. Заказ по счёту рабочий бот проводит в «Заказ выполнен», не дожидаясь
-- денег (решение владельца 2026-08-25) — сделку до конца ведёт основной
-- движок (`sync/engine.py`, `_step_move_realization_done`). Когда админ
-- привязывает оплату к заказу, рабочий бот снимает `awaiting_wire_payment`, но
-- в CRM за ним никто не возвращается (задача 11, ТЗ 2026-09-22). Два поля
-- держат состояние этой доводки:
--
--   payment_pending    — заказ по счёту, оплата по которому ещё не поступила
--                         на момент, когда сделку переводили в «Заказ
--                         выполнен». Ставит основной движок; NULL у связок,
--                         заведённых до этой миграции — для них решает
--                         текущая стадия сделки, а не этот флаг.
--   payment_synced_at  — когда робот довёл сделку до конца после прихода
--                         денег; NULL — ещё не доводил, второй раз не берём.
--
-- ТЗ 2026-09-22 «цепочка заказа», задача 11.

ALTER TABLE adminbot.amo_links
    ADD COLUMN IF NOT EXISTS payment_pending    boolean,
    ADD COLUMN IF NOT EXISTS payment_synced_at  timestamptz;
