-- Адрес сделки в таблицах связок. Применяется вручную:
--   psql "$ADMINBOT_DB_DSN" -f migrations/012_deal_address.sql
--
-- Зачем. Адрес заказа сегодня в базу рабочего бота не попадает: карточку клиента
-- никто не обновляет, мастера спрашивают адрес руками. Фактический адрес живёт
-- в сделке amoCRM — его туда кладёт календарный движок админ-бота, а этот же
-- робот (amo_sync) уже читает карточку сделки, когда её заполняет. Остаётся не
-- терять прочитанное: колонка хранит адрес сделки на момент, когда робот в неё
-- смотрел, и рабочий бот потом читает эту колонку по связке заказ ↔ сделка
-- (ТЗ 2026-09-16 «адреса до конца», задача 1).
--
-- Колонка — в обеих таблицах связок: химчистка и уборки идут одним и тем же
-- движком, разница только в таблице.

ALTER TABLE adminbot.amo_links      ADD COLUMN IF NOT EXISTS deal_address text;
ALTER TABLE adminbot.cleaning_links ADD COLUMN IF NOT EXISTS deal_address text;
