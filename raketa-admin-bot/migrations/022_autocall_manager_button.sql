-- Автозвонок: кнопка «Я уже перезвонил» в сообщении менеджеру.
-- ТЗ docs/plans/2026-10-23-autocall-manager-button.md (задача 2, 2026-10-23).
-- Применяется обёрткой обновления сама (шаг «4. Миграции» в deploy/update.sh),
-- а она гоняет ВСЕ миграции на каждом выкате — поэтому каждый шаг здесь
-- безопасен для повторного запуска.
--
-- Зачем (решение владельца 2026-10-23). Робот не дозвонился и собирается
-- повторить — менеджеру приходит одно сообщение с кнопкой, которое дальше
-- правится: пока впереди повтор — время повтора и кнопка, робот закончил —
-- итог без кнопки. Для этого цепочка помнит номер сообщения. Перед повтором
-- робот смотрит, не было ли звонка с клиентом после своей прошлой попытки, а
-- called_at при возврате в очередь обнуляется (движок, ветка Retry) — поэтому
-- время последней попытки хранится отдельно и возврат в очередь переживает.
--
--   last_called_at — когда робот отдал АТС команду последней попытки;
--   tg_message_id  — сообщение менеджеру с кнопкой в личке рабочего бота;
--                    NULL — такого сообщения по цепочке нет.
--
-- Новый финальный статус цепочки — 'cancelled' (робот остановился до повтора);
-- CHECK на status у таблицы нет, миграция для него не нужна.

ALTER TABLE adminbot.autocall_leads
    ADD COLUMN IF NOT EXISTS last_called_at timestamptz,  -- время последней попытки
    ADD COLUMN IF NOT EXISTS tg_message_id bigint;        -- сообщение менеджеру с кнопкой
