-- Отметки о разобранных удалениях заказов и уборок. Применяется вручную:
--   psql "$ADMINBOT_DB_DSN" -f migrations/014_order_deletions_seen.sql
--
-- Зачем своя таблица. Владелец удаляет неверно проведённый заказ в рабочем
-- боте, и робот должен освободить сделку в amoCRM (ТЗ 2026-09-17 «удаление
-- заказа освобождает сделку»). Заказ химчистки при этом пропадает из БД
-- физически, и рабочий бот кладёт след в свой регистр `public.deleted_orders`
-- (миграция 0012 рабочего бота); уборка остаётся строкой с `deleted_at`.
-- Хард-правило проекта не даёт админ-боту писать в схему `public` — снять
-- «неразобрано» там нечем, поэтому отметку о том, что удаление уже обработано,
-- он держит в своей схеме.
--
-- Почему составной ключ, а не просто `order_id`. Номера заказов химчистки
-- (`orders.id`) и уборок (`cleaning_orders.id`) пересекаются — заказ №5 и
-- уборка №5 существуют одновременно. Тот же урок уже учтён в
-- `adminbot.amo_links` / `adminbot.cleaning_links` (миграция 010) и в
-- `pending_order_reports` рабочего бота (миграция 0011, дефект найден ревью
-- 17.09): без явной колонки `kind` вторая запись молча замещала бы первую.
--
-- ТЗ 2026-09-17 «удаление заказа освобождает сделку», задача 3.

CREATE TABLE IF NOT EXISTS adminbot.order_deletions_seen (
    kind         text NOT NULL,                  -- 'order' | 'cleaning'
    order_id     bigint NOT NULL,
    processed_at timestamptz NOT NULL DEFAULT now(),
    outcome      text,                            -- что сделали — для разбора потом
    PRIMARY KEY (kind, order_id)
);
