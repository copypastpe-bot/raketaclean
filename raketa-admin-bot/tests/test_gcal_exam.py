"""Проверка самого экзамена: он должен ловить ту ошибку, ради которой написан.

Экзамен прогоняется руками по боевым записям (они содержат ПД и в git не лежат),
поэтому здесь проверяется его правило отбраковки — что считается «не заказом».
Если это правило ослабнет, экзамен начнёт показывать зелёный гейт на данных,
где робот заводит лишние сделки.
"""

from scripts.gcal_exam import is_not_order


def test_marks_that_can_never_be_an_order():
    for summary in ("⛔️Никита", "Сов! Перемыв, Наталья",
                    "⁉️Перенос(дату уточнить)Сов! Диван Наталья",
                    "Толстой с 9:00", "Русь с 9:00"):
        assert is_not_order({"summary": summary}), summary


def test_ordinary_orders_pass():
    for summary in ("Сов! Матрас, Юлия", "Ниж! Диван, Наталья", "Сов, Уборка, Андрей"):
        assert not is_not_order({"summary": summary}), summary
