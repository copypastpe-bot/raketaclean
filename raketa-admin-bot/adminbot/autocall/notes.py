"""След робота в самой сделке: чем закончилась цепочка автозвонка.

Зачем этот модуль есть. Связка АТС с амо раскладывает звонки по внутренним
номерам и знает ровно один — 100 «Амо». Робот же звонит менеджеру на
мобильный: иначе не срабатывает переадресация, потому что её правила
применяются только ко входящим звонкам, идущим по схеме АТС (стенд с
владельцем 2026-09-02). Такой звонок в карточку сделки не попадает вовсе —
на живой заявке 2026-09-02 вызов в истории АТС записан, а в амо его нет.
Пока это не решено на стороне onlinePBX, след в сделке оставляет сам робот
(решение владельца 2026-09-02).

Тексты для CRM живут рядом с движком, а не в `adminbot/tg/*_cards.py`: там
сообщения в Telegram, а здесь запись в чужой системе — тот же порядок, что
у календаря, ковров и заказов.

Модуль чистый: ни сети, ни времени внутри — момент звонка приходит
аргументом, поэтому каждая ветка проверяется обычным тестом.
"""

from __future__ import annotations

from datetime import datetime
from typing import Optional

from adminbot.amo.fields import MOSCOW_TZ

#: Итог цепочки → что робот пишет в сделку. Ключ для остановки (gave_up) —
#: причина из chain.NOTIFY_KINDS, для остальных финалов — статус цепочки.
_DEAL_NOTES: dict[str, str] = {
    "done":
        "Автозвонок: соединил менеджера с клиентом.",
    "no_contact":
        "Автозвонок: клиент дважды не ответил. Сделка переведена в "
        "«Не было 1-го касания».",
    "manager_unreachable":
        "Автозвонок: менеджер не ответил ни на один телефон. Робот остановился "
        "по этой заявке.",
    "attempts_exhausted":
        "Автозвонок: попытки звонка исчерпаны (4). Робот остановился.",
}


def deal_note_text(status: str, *, called_at: Optional[datetime] = None,
                   reason: Optional[str] = None) -> str:
    """Примечание в сделку по завершённой цепочке — одно на цепочку.

    Запись разговора в примечание не тянем: в API истории АТС ссылки на неё
    нет, она живёт в кабинете АТС — туда и отправляем читателя.

    Незнакомый статус — ValueError: пустое примечание в CRM хуже явной
    ошибки, потому что молча выглядит как «робот ничего не делал».
    """
    key = reason if status == "gave_up" else status
    try:
        head = _DEAL_NOTES[key]
    except KeyError:
        raise ValueError(
            f"нет текста примечания для финала цепочки: status={status!r}, "
            f"reason={reason!r}"
        ) from None

    lines = [head]
    if called_at is not None:
        moment = called_at.astimezone(MOSCOW_TZ).strftime("%d.%m %H:%M")
        lines.append(f"Звонок {moment} МСК, запись разговора — в кабинете АТС.")
    return "\n".join(lines)
